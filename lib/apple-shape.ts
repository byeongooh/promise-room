// ---------------- 크기에 따라 달라지는 것 ----------------
//
// 같은 사과를 20px 탭바에도, 200px 로그인 화면에도 그린다. 그런데 **같은
// 굵기·같은 장식으로 그리면 두 곳 중 하나는 반드시 망가진다.** 작은 쪽에서는
// 꼭지가 실처럼 사라지고, 큰 쪽에서는 억지로 굵힌 선이 뭉툭해 보인다.
//
// 그래서 "얼마나 크게 그리는가"를 받아 값을 돌려주는 함수로 둔다. 세 컴포넌트가
// 각자 숫자를 들고 있으면 언젠가 갈라지는데, 그건 이 파일을 만든 이유와 같다.
//
// 인자는 전부 **svg를 실제로 몇 px 폭으로 그리는지**다(viewBox 100 전체 기준).
// AppleGauge처럼 사과를 축소해 넣는 곳은 지름이 아니라 축소한 뒤의 폭을 넘긴다.

/**
 * 꼭지 굵기(viewBox 단위).
 *
 * 작을수록 굵어야 살아남는다. 실제 화면 픽셀로 환산하면 `width × 굵기 / 100`이라,
 * 20px 탭바에서 굵기 6은 1.2px밖에 안 된다 — 안티에일리어싱에 묻혀 회색 실이 된다.
 * 아래 값은 어느 크기에서든 꼭지가 최소 2px 안팎으로 남도록 잡은 것이다.
 */
export function stemWidth(renderedWidthPx: number): number {
  if (renderedWidthPx >= 90) return 6;
  if (renderedWidthPx >= 36) return 8;
  return 10;
}

/**
 * 광을 얹을지.
 *
 * 광은 폭의 7%짜리 타원이라 작은 사과에서는 4px도 안 된다. 그 크기에서는
 * "반질하다"가 아니라 그냥 얼룩으로 보이고, 사과를 오히려 지저분하게 만든다.
 * 탭바에서 이미 같은 이유로 빼고 있었는데, 그 판단을 크기 기준으로 옮긴 것이다.
 *
 * 48px은 광이 3.4px쯤 되는 지점이다. 이 아래로는 없는 편이 깨끗하다.
 */
export function showsShine(renderedWidthPx: number): boolean {
  return renderedWidthPx >= 48;
}

